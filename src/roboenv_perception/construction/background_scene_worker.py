"""Author an emissive display card, not reconstructed room geometry or collision."""

import argparse
import hashlib
import json
import math
import os
import shutil
import struct
from pathlib import Path


def scene_signature(stage, excluded="/World/EnvCreatorBackground"):
    """Bind composed values and connections of every pre-existing prim, including physics."""
    rows = {}
    for prim in stage.Traverse():
        if str(prim.GetPath()) == excluded or str(prim.GetPath()).startswith(excluded + "/"):
            continue
        rows[str(prim.GetPath())] = {
            "type": prim.GetTypeName(), "apis": list(prim.GetAppliedSchemas()),
            "attributes": {attr.GetName(): {"value": str(attr.Get()),
                            "samples": [(t, str(attr.Get(t))) for t in attr.GetTimeSamples()],
                            "connections": [str(p) for p in attr.GetConnections()]}
                           for attr in prim.GetAttributes()},
            "relationships": {rel.GetName(): [str(p) for p in rel.GetTargets()]
                              for rel in prim.GetRelationships()},
        }
    return rows


def author(scene: Path, image: Path, output: Path, camera_path: str, distance: float,
           hide_floor_visual: str | None = None):
    from pxr import Gf, Sdf, Usd, UsdGeom, UsdShade

    if not math.isfinite(distance) or not 0.5 <= distance <= 50:
        raise ValueError("display distance must be between 0.5 and 50 metres")
    original = Usd.Stage.Open(str(scene))
    if not original or not original.GetPrimAtPath("/World"):
        raise ValueError("background display requires a scene with /World")
    if UsdGeom.GetStageMetersPerUnit(original) != 1:
        raise ValueError("background display requires metre units")
    camera = UsdGeom.Camera(original.GetPrimAtPath(camera_path))
    if not camera or camera.GetProjectionAttr().Get() != UsdGeom.Tokens.perspective:
        raise ValueError("an existing perspective camera is required")
    clip = camera.GetClippingRangeAttr().Get()
    if not clip[0] < distance < clip[1]:
        raise ValueError("background display distance must be inside camera clipping range")
    target = "/World/EnvCreatorBackground"
    if original.GetPrimAtPath(target):
        raise ValueError("source already contains an EnvCreator background")
    source_hash = hashlib.sha256(scene.read_bytes()).hexdigest()
    before = scene_signature(original)
    shutil.copyfile(image, output / "background.png")
    stage = Usd.Stage.CreateNew(str(output / "scene.usda"))
    stage.GetRootLayer().subLayerPaths.append(Path(os.path.relpath(scene, output)).as_posix())
    stage.SetDefaultPrim(stage.GetPrimAtPath("/World"))
    UsdGeom.SetStageMetersPerUnit(stage, 1)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.GetStageUpAxis(original))
    if hide_floor_visual:
        floor = UsdGeom.Imageable(stage.GetPrimAtPath(hide_floor_visual))
        if not floor or not hide_floor_visual.startswith("/World/"):
            raise ValueError("hide_floor_visual must identify an existing floor prim under /World")
        floor.MakeInvisible()
    root = UsdGeom.Xform.Define(stage, target)
    camera_transform = UsdGeom.XformCache().GetLocalToWorldTransform(camera.GetPrim())
    width = distance * camera.GetHorizontalApertureAttr().Get() / camera.GetFocalLengthAttr().Get()
    height = distance * camera.GetVerticalApertureAttr().Get() / camera.GetFocalLengthAttr().Get()
    local = [(-width / 2, -height / 2, -distance), (width / 2, -height / 2, -distance),
             (width / 2, height / 2, -distance), (-width / 2, height / 2, -distance)]
    card = UsdGeom.Mesh.Define(stage, target + "/Display")
    parent_inverse = UsdGeom.XformCache().GetLocalToWorldTransform(stage.GetPrimAtPath("/World")).GetInverse()
    card.CreatePointsAttr([Gf.Vec3f(*parent_inverse.Transform(camera_transform.Transform(Gf.Vec3d(*p))))
                          for p in local])
    card.CreateFaceVertexCountsAttr([4])
    card.CreateFaceVertexIndicesAttr([0, 1, 2, 3])
    card.CreateDoubleSidedAttr(True)
    card.CreateSubdivisionSchemeAttr("none")
    uv = UsdGeom.PrimvarsAPI(card).CreatePrimvar("st", Sdf.ValueTypeNames.TexCoord2fArray,
                                               UsdGeom.Tokens.vertex)
    # Centre-crop to camera aspect instead of stretching a perspective picture.
    header = image.read_bytes()[:24]
    if header[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("background display expects a PNG generated by the completion stage")
    image_width, image_height = struct.unpack(">II", header[16:24])
    image_aspect = image_width / image_height
    span_u = min(1.0, (width / height) / image_aspect)
    span_v = min(1.0, image_aspect / (width / height))
    u0, v0 = (1 - span_u) / 2, (1 - span_v) / 2
    uv.Set([Gf.Vec2f(u0, v0), Gf.Vec2f(1 - u0, v0),
            Gf.Vec2f(1 - u0, 1 - v0), Gf.Vec2f(u0, 1 - v0)])
    mat = UsdShade.Material.Define(stage, target + "/Material")
    reader = UsdShade.Shader.Define(stage, target + "/Material/UV")
    reader.CreateIdAttr("UsdPrimvarReader_float2")
    reader.CreateInput("varname", Sdf.ValueTypeNames.Token).Set("st")
    reader.CreateOutput("result", Sdf.ValueTypeNames.Float2)
    tex = UsdShade.Shader.Define(stage, target + "/Material/Texture")
    tex.CreateIdAttr("UsdUVTexture")
    tex.CreateInput("file", Sdf.ValueTypeNames.Asset).Set(Sdf.AssetPath("./background.png"))
    tex.CreateInput("sourceColorSpace", Sdf.ValueTypeNames.Token).Set("sRGB")
    tex.CreateInput("st", Sdf.ValueTypeNames.Float2).ConnectToSource(reader.ConnectableAPI(), "result")
    tex.CreateOutput("rgb", Sdf.ValueTypeNames.Float3)
    shader = UsdShade.Shader.Define(stage, target + "/Material/Surface")
    shader.CreateIdAttr("UsdPreviewSurface")
    shader.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(Gf.Vec3f(0))
    shader.CreateInput("emissiveColor", Sdf.ValueTypeNames.Color3f).ConnectToSource(tex.ConnectableAPI(), "rgb")
    shader.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(1)
    mat.CreateSurfaceOutput().ConnectToSource(shader.ConnectableAPI(), "surface")
    UsdShade.MaterialBindingAPI.Apply(card.GetPrim()).Bind(mat)
    root.GetPrim().SetCustomDataByKey("envcreator:role", "visual_background_fixed_view_no_collision")
    stage.GetRootLayer().Save()
    reopened = Usd.Stage.Open(str(output / "scene.usda"))
    after = scene_signature(reopened)
    # Explicit visual override is allowed; every other original value remains identical.
    if hide_floor_visual:
        for snapshot in (before, after):
            snapshot[hide_floor_visual]["attributes"].pop("visibility", None)
    no_physics = not any("physics:" in a.GetName() for p in reopened.Traverse()
                         if str(p.GetPath()).startswith(target) for a in p.GetAttributes())
    checks = {"original_prims_unchanged": before == after,
              "source_layer_unchanged": source_hash == hashlib.sha256(scene.read_bytes()).hexdigest(),
              "background_has_no_physics": no_physics,
              "scene_reopens": bool(reopened), "texture_exists": (output / "background.png").is_file()}
    report = {"status": "authored" if all(checks.values()) else "failed", "checks": checks,
              "camera": camera_path, "distance_m": distance,
              "projection": "fixed_view_perspective_card_not_panorama",
              "camera_aspect": width / height,
              "image_fit": "centre_crop_to_camera_aspect", "uv_crop": [u0, v0, 1 - u0, 1 - v0],
              "lighting": "existing_lights_unchanged; emissive_visual_card",
              "hidden_floor_visual": hide_floor_visual,
              "original_prim_comparison": "all composed properties except explicitly requested floor visibility",
              "limits": ["No room mesh, depth or collision inferred.",
                         "No correct parallax when the camera translates or turns away.",
                         "Emissive card may affect indirect renderer light; image comparison required."],
              "physics_execution": "not_run", "simulator_render": "not_run"}
    (output / "display.json").write_text(json.dumps(report, indent=2) + "\n")
    if not all(checks.values()):
        raise RuntimeError("background scene invariants failed")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scene", type=Path, required=True)
    parser.add_argument("--image", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--camera", required=True)
    parser.add_argument("--distance", type=float, default=4.0)
    parser.add_argument("--hide-floor-visual", help="Hide only this existing floor's appearance, preserving collision")
    args = parser.parse_args()
    author(args.scene.resolve(strict=True), args.image.resolve(strict=True), args.output.resolve(),
           args.camera, args.distance, args.hide_floor_visual)
